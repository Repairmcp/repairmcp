#!/usr/bin/env node
/**
 * Generate the D1 data-import migration from the served corpus.
 *
 * Source: apps/deg-server/data/deg-inquiries-full.json — the transform output.
 * Output: apps/deg-server/migrations/0002_data.sql       (the corpus)
 *         apps/deg-server/migrations/0005_meta_data.sql  (what it says about itself)
 *
 * The transform output is the source of truth for what gets served, so the
 * remote corpus is generated from the same file the local STDIO server loads
 * rather than from SQLite directly. That is what makes it impossible for local
 * and remote to disagree about a record: there is one producer.
 *
 * This script never opens C:\degdata\deg.sqlite. It reads JSON only.
 *
 * Run from repo root:
 *   npx tsx scripts/build-d1-sql.ts --dry-run
 *   npx tsx scripts/build-d1-sql.ts
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEGInquirySchema, type DEGInquiry } from '../packages/deg/src/schema.js';
import { deriveCorpusMeta } from '../packages/deg/src/freshness.js';
import {
  CORPUS_META_KEYS,
  INQUIRY_COLUMNS,
  inquiryToRow,
  type InquiryRow,
} from '../packages/deg/src/d1/sql.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');

const IN_PATH = join(REPO_ROOT, 'apps', 'deg-server', 'data', 'deg-inquiries-full.json');
const OUT_PATH = join(REPO_ROOT, 'apps', 'deg-server', 'migrations', '0002_data.sql');
const META_OUT_PATH = join(
  REPO_ROOT,
  'apps',
  'deg-server',
  'migrations',
  '0005_meta_data.sql',
);

const DRY_RUN = process.argv.includes('--dry-run');

/**
 * D1 caps a single SQL statement at 100 KB. We chunk to 80 KB to leave room —
 * the cap is on the statement as D1 receives it, and being 20% shy of a hard
 * limit costs nothing when the whole file is one sequential import.
 */
const MAX_STATEMENT_BYTES = 80_000;

/** Hard ceiling. A single row that cannot fit is a stop-the-line error. */
const D1_STATEMENT_LIMIT = 100_000;

/**
 * SQLite string literal. Doubling single quotes is the whole escape rule for
 * SQLite — there are no backslash escapes. Newlines and tabs are legal inside a
 * literal and are left alone; anything else in the C0 range is rejected rather
 * than escaped, because its presence means the corpus changed shape upstream
 * and that deserves a look, not a silent workaround.
 */
function lit(v: string | number | null): string {
  if (v === null) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

function findIllegalControlChar(s: string): number | null {
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c < 32 && c !== 9 && c !== 10 && c !== 13) return c;
    if (c === 127) return c;
  }
  return null;
}

function rowValues(row: InquiryRow): string {
  const parts: string[] = [];
  for (const col of INQUIRY_COLUMNS) {
    const v = row[col];
    if (typeof v === 'string') {
      const bad = findIllegalControlChar(v);
      if (bad !== null) {
        throw new Error(
          `db_id=${row.db_id} column ${col} contains control character U+${bad
            .toString(16)
            .padStart(4, '0')}. The corpus has always been free of these; ` +
            `investigate the parser before changing this script.`,
        );
      }
    }
    parts.push(lit(v));
  }
  return `(${parts.join(',')})`;
}

/**
 * The freshness migration: what the corpus will tell every model about itself.
 *
 * `DELETE` rather than `DROP`/`CREATE` so this file is safe to apply on its own
 * against a live database — the common case after a sync is regenerating 0002
 * and this, and only this one needs to land for the served dates to move.
 */
function buildMetaSql(inquiries: DEGInquiry[]): string {
  const meta = deriveCorpusMeta(inquiries);
  if (!meta) {
    throw new Error(
      'could not derive corpus freshness: no effective date, or no crawl timestamp ' +
        '(lastSeenAt / scrapedAt / bodyFetchedAt) anywhere in the corpus. The server ' +
        'would serve without stating a cutoff, which is the failure this table exists ' +
        'to prevent — fix the transform rather than shipping the corpus without it.',
    );
  }

  const values: Array<[string, string]> = [
    [CORPUS_META_KEYS.currentThrough, meta.currentThrough],
    [CORPUS_META_KEYS.syncedAt, meta.syncedAt],
    [CORPUS_META_KEYS.recordCount, String(meta.recordCount)],
  ];

  return (
    [
      '-- 0005_meta_data.sql — GENERATED by scripts/build-d1-sql.ts. Do not edit by hand.',
      `-- Source: apps/deg-server/data/deg-inquiries-full.json (${meta.recordCount} records)`,
      '-- Apply after 0004_meta.sql. Safe to re-apply alone after a corpus refresh.',
      '--',
      `-- Set CORPUS_VERSION in wrangler.jsonc to "${meta.syncedAt}" to match; /health`,
      '-- reports corpusVersionStale until it does.',
      '',
      'DELETE FROM corpus_meta;',
      '',
      'INSERT INTO corpus_meta (key, value) VALUES',
    ].join('\n') +
    '\n' +
    values.map(([k, v]) => `  (${lit(k)},${lit(v)})`).join(',\n') +
    ';\n'
  );
}

function main(): void {
  if (!existsSync(IN_PATH)) {
    console.error(`Corpus not found: ${IN_PATH}`);
    console.error('Run `npx tsx scripts/transform-deg-sqlite.ts` first.');
    process.exit(1);
  }

  console.log(`Reading ${IN_PATH}`);
  const raw = JSON.parse(readFileSync(IN_PATH, 'utf-8'));
  const inquiries: DEGInquiry[] = DEGInquirySchema.array().parse(raw);
  console.log(`Parsed ${inquiries.length} inquiries.\n`);

  const insertPrefix = `INSERT INTO inquiry (${INQUIRY_COLUMNS.join(',')}) VALUES\n`;

  const statements: string[] = [];
  let current: string[] = [];
  let currentBytes = insertPrefix.length;
  let largestRow = 0;

  for (const inq of inquiries) {
    const values = rowValues(inquiryToRow(inq));
    const size = values.length + 2; // ',\n'
    if (size > largestRow) largestRow = size;

    if (size + insertPrefix.length > D1_STATEMENT_LIMIT) {
      throw new Error(
        `inquiry ${inq.id} serializes to ${size} bytes, over D1's ${D1_STATEMENT_LIMIT}-byte ` +
          `statement limit. It cannot be imported as a single INSERT.`,
      );
    }

    if (current.length > 0 && currentBytes + size > MAX_STATEMENT_BYTES) {
      statements.push(insertPrefix + current.join(',\n') + ';');
      current = [];
      currentBytes = insertPrefix.length;
    }

    current.push(values);
    currentBytes += size;
  }
  if (current.length > 0) statements.push(insertPrefix + current.join(',\n') + ';');

  const header = [
    '-- 0002_data.sql — GENERATED by scripts/build-d1-sql.ts. Do not edit by hand.',
    `-- Source: apps/deg-server/data/deg-inquiries-full.json (${inquiries.length} records)`,
    '-- Apply after 0001_schema.sql and before 0003_fts.sql.',
    '-- Contains no explicit transaction statements; D1 supplies its own.',
    '',
  ].join('\n');

  const body = header + statements.join('\n\n') + '\n';

  // wrangler rejects the whole file if the raw text contains this phrase — the
  // check is a bare `sql.includes()` that does not skip comments or string
  // literals, and its one-shot `.replace()` cannot remove a second occurrence.
  // A DEG inquiry quoting it would be enough. Catch that here, where the
  // message can say why, rather than at import time where it cannot.
  const TRANSACTION_MARKER = ['BEGIN', 'TRANSACTION'].join(' ');
  if (body.includes(TRANSACTION_MARKER)) {
    throw new Error(
      `generated SQL contains the literal "${TRANSACTION_MARKER}", which wrangler ` +
        `refuses even inside a comment or a quoted string. Find the record and ` +
        `decide how to escape it before importing.`,
    );
  }

  const metaSql = buildMetaSql(inquiries);
  const meta = deriveCorpusMeta(inquiries)!;

  const maxStatement = statements.reduce((m, s) => Math.max(m, s.length), 0);

  console.log('=== Generation summary ===');
  console.log(`Records:               ${inquiries.length}`);
  console.log(`Corpus current through: ${meta.currentThrough}`);
  console.log(`Corpus last synced:     ${meta.syncedAt}   <- set CORPUS_VERSION to this`);
  console.log(`INSERT statements:     ${statements.length}`);
  console.log(`Largest statement:     ${maxStatement.toLocaleString()} bytes (limit ${D1_STATEMENT_LIMIT.toLocaleString()})`);
  console.log(`Largest single row:    ${largestRow.toLocaleString()} bytes`);
  console.log(`Total file size:       ${(body.length / 1_048_576).toFixed(1)} MB`);

  if (maxStatement > D1_STATEMENT_LIMIT) {
    throw new Error(`generated a ${maxStatement}-byte statement, over D1's limit`);
  }

  if (DRY_RUN) {
    console.log(`\nDry run — nothing written. Would write:`);
    console.log(`  ${OUT_PATH}`);
    console.log(`  ${META_OUT_PATH}`);
    console.log('\n--- 0005_meta_data.sql would contain ---');
    console.log(metaSql);
    return;
  }

  const outDir = dirname(OUT_PATH);
  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  writeFileSync(OUT_PATH, body, 'utf-8');
  console.log(`\nWrote ${OUT_PATH}`);
  writeFileSync(META_OUT_PATH, metaSql, 'utf-8');
  console.log(`Wrote ${META_OUT_PATH}`);
}

main();
